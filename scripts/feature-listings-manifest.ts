/**
 * The listings that name one feature of a larger site, recorded in D1 (serpcompany/best.serp.co#409).
 *
 *   pnpm catalog:feature-listings
 *       write d1/publications/2026-10-12-feature-listings.yaml from #349's reviewed mapping
 *       (`featureListings` in d1/hygiene/2026-10-10-taxonomy.yaml)
 *
 * #349's mapping names 83 listings that each name one feature, add-on, model, or sub-tool of a
 * larger site (Einstein GPT on salesforce.com): their host's traffic measures the parent product,
 * so no best page pins them. Each gets one `listing-feature-listing-set`, which sets
 * `listings.is_feature_listing` where it is still unset; the admin pin picker and its server check
 * read that column (#405).
 *
 * The manifest is row-level (`concurrency: rows`): each operation expects the listing's id, slug,
 * and an unset flag, and refuses its whole batch otherwise, so one file applies on staging and
 * production alike. It reads only committed files: no D1.
 */
import { readFileSync, writeFileSync } from 'node:fs'
import { resolve } from 'node:path'
import { fileURLToPath } from 'node:url'
import { parse, stringify } from 'yaml'
import { buildPublicationPlan, parseManifest } from './d1-publisher'

export const FEATURE_LISTINGS_MAPPING = 'd1/hygiene/2026-10-10-taxonomy.yaml'
export const FEATURE_LISTINGS_MANIFEST_ID = '2026-10-12-feature-listings'

/** One of the mapping's `featureListings`. */
export interface FeatureListing {
  id: string
  slug: string
  /** The feature the listing names (Amazon Polly on aws.amazon.com). */
  name: string
  reason: string
}

/** The mapping's `featureListings`, in its order. */
export function readFeatureListings(path = FEATURE_LISTINGS_MAPPING): FeatureListing[] {
  const mapping = parse(readFileSync(resolve(path), 'utf8')) as {
    featureListings?: FeatureListing[]
  }
  if (!mapping.featureListings?.length) throw new Error(`${path} has no featureListings.`)
  return mapping.featureListings
}

/** The manifest's source, which the publisher accepts (planned at any publication state). */
export function buildFeatureListingsManifest(features: readonly FeatureListing[]): string {
  const ids = new Set<string>()
  for (const entry of features) {
    if (ids.has(entry.id)) throw new Error(`${entry.slug} (${entry.id}) is listed twice.`)
    ids.add(entry.id)
  }
  const operations = features.map(entry => ({
    action: 'listing-feature-listing-set',
    id: entry.id,
    slug: entry.slug,
    reason: `#409, from #349's mapping: ${entry.name} ${entry.reason}`,
    expected: false,
    featureListing: true
  }))
  const manifest = {
    version: 1,
    id: FEATURE_LISTINGS_MANIFEST_ID,
    concurrency: 'rows',
    provenance: { actor: 'devinschumacher', workflow: 'github/publish-d1' },
    operations
  }
  const source = `# serpcompany/best.serp.co#409: mark the ${operations.length} listings that name one feature, add-on, model,
# or sub-tool of a larger site (#349's \`featureListings\` in ${FEATURE_LISTINGS_MAPPING}),
# which a best page never pins, in D1 (\`listings.is_feature_listing\`) instead of in app code.
# Each listing-feature-listing-set compares and swaps the listing's slug and its unset flag, refuses
# a listing that isn't approved, keeps its checksum and lastmod (no public page changes), and logs
# "Details edited: feature listing".
# Generated by \`pnpm catalog:feature-listings\` from the mapping. Row-level: a listing whose slug or
# flag changed since refuses the whole batch, with nothing written. It needs migration
# 0015_feature_listings, so publish it only after the deploy that applied it: on staging first,
# then on production after promotion and Deploy Production.
${stringify(manifest, { aliasDuplicateObjects: false, lineWidth: 0 })}`
  buildPublicationPlan(parseManifest(source), source, new Date().toISOString(), {
    checksum: 'a'.repeat(64),
    version: 1
  })
  return source
}

if (process.argv[1] && fileURLToPath(import.meta.url) === resolve(process.argv[1])) {
  const path = resolve('d1/publications', `${FEATURE_LISTINGS_MANIFEST_ID}.yaml`)
  writeFileSync(path, buildFeatureListingsManifest(readFeatureListings()))
  console.log(`Wrote d1/publications/${FEATURE_LISTINGS_MANIFEST_ID}.yaml`)
}
