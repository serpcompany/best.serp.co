/**
 * Worker entry: canonical-host and trailing-slash redirects, the environment's crawl policy,
 * then the OpenNext-generated handler behind a catalog-epoch-keyed edge cache. Its cron hosts
 * queued listing media, and locally it serves the media bucket at `/_media` (#95).
 *
 * Admin paths pass the Cloudflare Access and session-cookie gate first (`lib/auth/admin-gate.ts`).
 *
 * `scheduled()` serves the Cron Triggers in `wrangler.jsonc` (`triggers.crons`): the hourly draft
 * reminders and expiry (#63), the listing media queue every 15 minutes (#95), and the weekly
 * badge program (#66) with its daily rechecks, in `lib/worker/scheduled.ts`.
 *
 * Wrangler's `main` points here (OpenNext "custom worker" pattern); `.open-next/worker.js`
 * and `.next/routes-manifest.json` are generated by `opennextjs-cloudflare build`. This file
 * is excluded from `tsc` because it imports that build output, so it only wires that output
 * in: the pipeline lives in `lib/worker/handle-request.ts`, `lib/worker/catalog.ts`,
 * `lib/routing/`, `lib/environment/`, and `lib/edge-cache/html-cache.ts`, which are
 * type-checked and unit-tested, and it keeps no state of its own (#165). See docs/ARCHITECTURE.md#environments-and-hosts,
 * docs/ARCHITECTURE.md#url-canonicalization, and docs/ARCHITECTURE.md#caching.
 */
// Generated by `next build` (inside `opennextjs-cloudflare build`); OpenNext reads the same file.
import routesManifest from './.next/routes-manifest.json'
// @ts-expect-error generated by `opennextjs-cloudflare build`
import openNextWorker from './.open-next/worker.js'
import { withEdgeCache } from './lib/edge-cache/html-cache'
import { serveLocalMedia } from './lib/media/worker-media'
import { configRedirectPatterns } from './lib/routing/trailing-slash'
import { catalogEpochReader, catalogRenderer } from './lib/worker/catalog'
import { handleWorkerRequest } from './lib/worker/handle-request'
import { handleScheduled, type ScheduledEnv } from './lib/worker/scheduled'

// @ts-expect-error generated by `opennextjs-cloudflare build`
export { BucketCachePurge, DOQueueHandler, DOShardedTagCache } from './.open-next/worker.js'

const EDGE_CACHE_NAME = 'edge-html'
/**
 * next.config.ts redirects, which send moved URLs to their canonical page in one hop. A
 * malformed manifest throws here, at startup, so the deploy and every request fail loudly
 * instead of the trailing-slash rule silently switching off.
 */
const configRedirects = loadConfigRedirects()

interface WorkerEnv {
  CANONICAL_HOST_REDIRECT?: string
  CF_ACCESS_AUD?: string
  CF_ACCESS_REQUIRED?: string
  CF_ACCESS_TEAM_DOMAIN?: string
  CF_VERSION_METADATA?: { id?: string }
  D1_RUNTIME_ENV?: string
  DB?: D1Database
  MEDIA?: R2Bucket
  SITE_ENVIRONMENT?: string
}

function loadConfigRedirects(): RegExp[] {
  try {
    return configRedirectPatterns(routesManifest)
  } catch (error) {
    console.error(
      JSON.stringify({
        event: 'routes_manifest_invalid',
        message: error instanceof Error ? error.message : String(error)
      })
    )
    throw error
  }
}

function log(event: object): void {
  console.info(JSON.stringify(event))
}

export default {
  scheduled(
    controller: ScheduledController,
    env: WorkerEnv & ScheduledEnv,
    context: ExecutionContext
  ): Promise<void> {
    return handleScheduled(controller, env, context)
  },

  async fetch(request: Request, env: WorkerEnv, context: ExecutionContext): Promise<Response> {
    // Local only: the media bucket has no public host there (lib/media/worker-media.ts).
    const localMedia = await serveLocalMedia(request, env)
    if (localMedia) return localMedia
    const render = catalogRenderer(
      env,
      rendered => openNextWorker.fetch(rendered, env, context),
      log
    )
    return handleWorkerRequest(request, env, {
      configRedirects,
      // Redirects and the non-production robots.txt are answered before this, so they are
      // never rendered or stored. A cacheable request reaches OpenNext with allowlisted
      // headers only (`renderRequestFor` in lib/edge-cache/html-cache.ts).
      serve: async served => {
        const cache = await caches.open(EDGE_CACHE_NAME)
        return withEdgeCache(
          served,
          context,
          {
            cache,
            deploymentId: env.CF_VERSION_METADATA?.id || 'unversioned',
            epoch: catalogEpochReader(env, cache, log),
            observe: log
          },
          render
        )
      }
    })
  }
}
